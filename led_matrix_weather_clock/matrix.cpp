void drawDigit(int digit, int startX, int startY, CRGB color) {
  if (digit < 0 || digit > 9) return;
  for (int y = 0; y < 7; y++)
    for (int x = 0; x < 5; x++)
      if (digits[digit][y][x]) setPixel(startX + x, startY + y, color);
}

void drawNumber(int num, CRGB color) {
  FastLED.clear();
  char str[6];
  snprintf(str, sizeof(str), "%d", num);
  int len = strlen(str);
  int totalWidth = len * 6;
  int startX = (MATRIX_W - totalWidth) / 2;
  for (int i = 0; i < len; i++) {
    char c = str[i];
    if (c == '-') setPixel(startX + i * 6 + 2, 3, color); else {
      drawDigit(c - '0', startX + i * 6, 0, color);
    }
  }
}

